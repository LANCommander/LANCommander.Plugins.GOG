using System.Text;
using LANCommander.GOG.Manifest;
using LANCommander.SDK.Enums;

namespace LANCommander.GOG.Packaging;

/// <summary>
/// Composes the uninstall script from the deletion flags the installer attaches to its registry
/// writes.
/// </summary>
/// <remarks>
/// There is no translated equivalent to work from: Inno Setup's uninstaller is a separate program
/// built at compile time, and this library reads the installer rather than it. What the installer
/// does record is which of its registry writes it expects to be undone, which is enough to take
/// back what the install script put down.
/// </remarks>
public static class UninstallScriptComposer
{
    /// <summary>
    /// Composes the uninstall script, or returns <see langword="null"/> when the installer marks
    /// nothing for removal.
    /// </summary>
    public static ComposedScript? Compose(InstallerManifest manifest, string installerFileName)
    {
        var unresolved = new SortedSet<string>(StringComparer.OrdinalIgnoreCase);

        var entries = manifest.RegistryEntries
            .Where(entry => Removes(entry.Options))
            .ToList();

        if (entries.Count == 0)
            return null;

        var output = new StringBuilder();

        output.AppendLine("<#")
            .AppendLine("    Uninstall script generated by the LANCommander GOG plugin.")
            .AppendLine()
            .AppendLine($"    Source:       {installerFileName}")
            .AppendLine($"    Inno Setup:   {manifest.InnoVersion}")
            .AppendLine()
            .AppendLine("    Removes the registry writes the installer marked for deletion on uninstall.")
            .AppendLine("#>")
            .AppendLine();

        foreach (var group in entries.GroupBy(entry => entry.FullKeyPath, StringComparer.OrdinalIgnoreCase))
        {
            var key = PowerShellText.Argument(PowerShellText.RegistryPath(group.Key), unresolved);

            foreach (var entry in group.Where(entry =>
                         entry.Options.HasFlag(RegistryEntryOptions.UninsDeleteValue)
                         || entry.Options.HasFlag(RegistryEntryOptions.UninsClearValue))
                     .Where(entry => entry.ValueName.Length > 0))
                output.AppendLine(
                    $"Remove-ItemProperty -Path {key} " +
                    $"-Name {PowerShellText.Argument(entry.ValueName, unresolved)} -ErrorAction SilentlyContinue");

            if (group.Any(entry => entry.Options.HasFlag(RegistryEntryOptions.UninsDeleteEntireKey)))
                output.AppendLine($"Remove-Item -Path {key} -Recurse -ErrorAction SilentlyContinue");
            else if (group.Any(entry => entry.Options.HasFlag(RegistryEntryOptions.UninsDeleteEntireKeyIfEmpty)))
                EmitRemoveIfEmpty(output, key);

            output.AppendLine();
        }

        var warnings = unresolved
            .Select(constant =>
                $"{constant} is an Inno Setup constant with no stand-in outside the installer. " +
                "It is written into the uninstall script as-is.")
            .ToList();

        var requiresAdmin = entries.Any(entry => entry.Root == RegistryRoot.LocalMachine);

        return new ComposedScript(ScriptType.Uninstall, output.ToString(), requiresAdmin, warnings);
    }

    /// <summary>
    /// Removes a key only when nothing is left under it, which is what the installer asked for.
    /// </summary>
    private static void EmitRemoveIfEmpty(StringBuilder output, string key)
    {
        output.AppendLine($"$key = Get-Item -Path {key} -ErrorAction SilentlyContinue")
            .AppendLine("if ($key -and $key.ValueCount -eq 0 -and $key.SubKeyCount -eq 0) {")
            .AppendLine($"    Remove-Item -Path {key} -ErrorAction SilentlyContinue")
            .AppendLine("}");
    }

    /// <summary>True when the installer marked an entry to be undone on uninstall.</summary>
    private static bool Removes(RegistryEntryOptions options)
        => options.HasFlag(RegistryEntryOptions.UninsDeleteValue)
           || options.HasFlag(RegistryEntryOptions.UninsClearValue)
           || options.HasFlag(RegistryEntryOptions.UninsDeleteEntireKey)
           || options.HasFlag(RegistryEntryOptions.UninsDeleteEntireKeyIfEmpty);
}
